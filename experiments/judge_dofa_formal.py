"""Judge the formal DOFA arm against paper/DOFA_FORMAL_DESIGN.md (frozen 2026-11-08) and write results/RESULTS_DOFA_FORMAL.md.

    QW2_MAP=probe ~/miniforge3/envs/favela/bin/python -u -B experiments/judge_dofa_formal.py

Coverage is pooled over the 100 splits (sum covered / sum selected), as in figures/fig_data.py; counts use the unrounded pooled
estimates. The counted methods are those of Fig. 4 (results/main_*, bl_main_*, scg_main_*_l1fix); Mondrian CP (md_main_*) is
reported, not counted, as in the paper. Quota and budget rules follow each setting's policy direction (bottom for dofa_poverty
and dofa_usavars), as in the exploratory arm. E6 refits the probe on the first ten splits exactly as run_main.one does and
compares GROUND's own linear head on the test units outside GROUND's in_train.
"""
import os
import sys

os.environ.setdefault("QW2_MAP", "probe")
import numpy as np                                                    # noqa: E402
import pandas as pd                                                   # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(ROOT, "figures")); sys.dont_write_bytecode = True
import data as DS                                                     # noqa: E402
import fig_data as FD                                                 # noqa: E402
import run_main as RM                                                 # noqa: E402

NAMES = ["dofa_poverty", "dofa_m3leo", "dofa_floods", "dofa_usavars"]
MEASURED = ["dofa_poverty", "dofa_floods"]
METHODS = ["SCP |res|", "SCP stud", "CQR", "BY stud", "GeoCP", "LSCP", "RLCP", "Regression kriging", "QRF",
           "Bootstrap ensemble + residual", "JOMI stud", "SC-GeoCCP"]
SHORT = {"SCP |res|": "Split CP", "SCP stud": "Normalized CP", "BY stud": "BY", "Regression kriging": "Regression kriging",
         "Bootstrap ensemble + residual": "Bootstrap ensemble", "JOMI stud": "JOMI"}
TAG = {"dofa_poverty": "DHS wealth (13 countries)", "dofa_m3leo": "M3LEO biomass†", "dofa_floods": "UrbanSARFloods",
       "dofa_usavars": "USAVars tree cover†"}
OUT = os.path.join(ROOT, "results", "RESULTS_DOFA_FORMAL.md")


def rules(nm):
    p = DS.POLICY[nm]
    return {"policy 5%": f"{p}5", "policy 1%": f"{p}1", "policy 20%": f"{p}20",
            "quota": "quota_bottom" if p == "bottom" else "quota",
            "budget": "knapsack_need" if p == "bottom" else "knapsack",
            "mask (tuned h)": "mask_h2", "mask (base h)": "mask_base"}


def cov(P, rule, m, col="cov"):
    return float(P.loc[(rule, m), col]) if (rule, m) in P.index else np.nan


def fmt(x, d=3):
    return "–" if not np.isfinite(x) else f"{x:.{d}f}"


def probe_r2(nm, reps=10):
    """Test-unit R² of the probe (run_main.fit_mu_sigma on the split of run_main.one) and of GROUND's head."""
    d = DS.load(nm); X, y, N = d["Xrf"], d["y"], d["N"]
    z = np.load(os.path.join(DS.GROUND_8DS, DS.DOFA[nm] + "_scores.npz"), allow_pickle=False)
    N0 = len(z["y"])
    idx = np.sort(np.random.default_rng(0).choice(N0, DS.NMAX, replace=False)) if N0 > DS.NMAX else np.arange(N0)
    assert np.allclose(z["y"][idx], y)
    gp, intr = z["y_pred"][idx].astype(float), z["in_train"][idx]
    r2 = lambda a, b: 1 - np.sum((a - b) ** 2) / np.sum((a - a.mean()) ** 2)          # noqa: E731
    out = []
    for rep in range(reps):
        rng = np.random.default_rng([2027, rep, DS.ALL.index(nm)])
        perm = rng.permutation(N); ntr, nca = int(0.4 * N), int(0.3 * N)
        Dtr, T = perm[:ntr], perm[ntr + nca:]
        mu, _ = RM.fit_mu_sigma(X, y, Dtr, rng)
        Tg = T[~intr[T]]
        out.append((r2(y[T], mu[T]), r2(y[Tg], gp[Tg]), r2(y[Tg], mu[Tg])))
    return np.mean(out, axis=0)


def main():
    P = {nm: FD.pooled(FD.runs(nm)) for nm in NAMES}
    L = ["# Formal DOFA arm: results (paper/DOFA_FORMAL_DESIGN.md, frozen 2026-11-08)", "",
         "Maps: frozen DOFA features (PCA-32 of the backbone output) with a ridge probe refitted on the training fold of every "
         "split; 100 random splits 40/30/30; coverage of 90% intervals among the selected test units, pooled over splits. "
         "† label is a product (model output). Generated by `experiments/judge_dofa_formal.py`.", ""]
    # E1
    r5 = {nm: rules(nm)["policy 5%"] for nm in NAMES}
    L += ["## E1 Coverage at the selected 5% (policy direction)", "",
          "| Method | " + " | ".join(f"{TAG[nm]} ({r5[nm]})" for nm in NAMES) + " | below 0.85 (of 4) | below 0.85, measured (of 2) |",
          "|---|" + "---|" * (len(NAMES) + 2)]
    counts = {}
    for m in METHODS:
        v = [cov(P[nm], r5[nm], m) for nm in NAMES]
        n4 = int(sum(x < 0.85 for x in v if np.isfinite(x)))
        n2 = int(sum(cov(P[nm], r5[nm], m) < 0.85 for nm in MEASURED if np.isfinite(cov(P[nm], r5[nm], m))))
        counts[m] = (n4, n2)
        L.append(f"| {SHORT.get(m, m)} | " + " | ".join(fmt(x) for x in v) + f" | {n4} | {n2} |")
    md = []
    for nm in NAMES:
        f = os.path.join(ROOT, "results", f"md_main_{nm}.csv")
        if os.path.exists(f):
            x = pd.read_csv(f); x = x[x.rule == r5[nm]]
            g = x.groupby("method")
            md.append({m: g.n_cov.sum()[m] / g.n_sel.sum()[m] for m in g.groups})
        else:
            md.append({})
    for m in sorted({k for d in md for k in d}):
        L.append(f"| {m} (reported, not counted) | " + " | ".join(fmt(d.get(m, np.nan)) for d in md) + " | | |")
    # E2
    L += ["", "## E2 Settings below 0.85 under the other rules (of 4; – = method not run on that rule)", "",
          "| Method | " + " | ".join(k for k in rules(NAMES[0]) if k != "policy 5%") + " |",
          "|---|" + "---|" * (len(rules(NAMES[0])) - 1)]
    for m in METHODS:
        cells = []
        for k in rules(NAMES[0]):
            if k == "policy 5%":
                continue
            v = [cov(P[nm], rules(nm)[k], m) for nm in NAMES]
            cells.append("–" if not any(np.isfinite(v)) else str(int(sum(x < 0.85 for x in v if np.isfinite(x)))))
        L.append(f"| {SHORT.get(m, m)} | " + " | ".join(cells) + " |")
    # E3
    L += ["", "## E3 Width relative to JOMI at the selected 5% (mean finite half-width; median over the four settings)", "",
          "| Method | width / JOMI | " + " | ".join(TAG[nm] for nm in NAMES) + " |", "|---|---|" + "---|" * len(NAMES)]
    for m in METHODS:
        v = [cov(P[nm], r5[nm], m, "width") / cov(P[nm], r5[nm], "JOMI stud", "width") for nm in NAMES]
        L.append(f"| {SHORT.get(m, m)} | {fmt(np.nanmedian(v), 2)} | " + " | ".join(fmt(x, 2) for x in v) + " |")
    L.append("| JOMI infinite share | | " + " | ".join(fmt(cov(P[nm], r5[nm], 'JOMI stud', 'inf')) for nm in NAMES) + " |")
    # E4
    L += ["", f"## E4 Worst group under the policy-direction quota (groups selected at least {FD.NMIN} times)", "",
          "| Method | " + " | ".join(TAG[nm] for nm in NAMES) + " |", "|---|" + "---|" * len(NAMES)]
    for m in ["JOMI stud", "SC-GeoCCP"]:
        cells = []
        for nm in NAMES:
            g = FD.groups(nm, "state", main=["JOMI stud"])
            g = g[(g.rule == rules(nm)["quota"]) & (g.method == m)].groupby("group")[["n", "c"]].sum()
            g = g[g.n >= FD.NMIN]
            cells.append(f"{(g.c / g.n).min():.3f} ({len(g)} groups)" if len(g) else "–")
        L.append(f"| {SHORT.get(m, m)} | " + " | ".join(cells) + " |")
    # E5
    f = os.path.join(ROOT, "results", "cfbh_dofa_poverty.csv")
    if os.path.exists(f):
        c = pd.read_csv(f)
        s = c.groupby(["rule", "method"]).agg(FDR=("fdp", "mean"), funded=("n_fund", "mean"),
                                               reached=("n_fund_elig", "sum"), elig=("n_elig", "sum"))
        s["eligible reached"] = s.reached / s.elig
        L += ["", "## E5 Funding among the selected villages, dofa_poverty (FDR = share of funded villages not eligible)", "",
              "| Rule | Method | FDR | funded per split | eligible reached |", "|---|---|---|---|---|"]
        L += [f"| {r} | {m} | {x.FDR:.3f} | {x.funded:.1f} | {x['eligible reached']:.3f} |" for (r, m), x in s.iterrows()]
    # E6
    L += ["", "## E6 Map accuracy: test-unit R², mean of the first ten splits", "",
          "| Setting | probe (all test units) | GROUND head (test units outside its in_train) | probe (same units) |",
          "|---|---|---|---|"]
    for nm in NAMES:
        a, b, c3 = probe_r2(nm)
        L.append(f"| {TAG[nm]} | {a:.3f} | {b:.3f} | {c3:.3f} |")
    # judgement
    jomi = [cov(P[nm], r5[nm], "JOMI stud") for nm in NAMES]; scg = [cov(P[nm], r5[nm], "SC-GeoCCP") for nm in NAMES]
    P1 = all(x >= 0.85 for x in jomi + scg)
    nsp, ngeo = counts["SCP |res|"][0], counts["GeoCP"][0]
    P2 = max(nsp, ngeo) >= 1
    P3 = counts["SCP stud"][0] < nsp and counts["Bootstrap ensemble + residual"][0] < nsp
    L += ["", "## Judgement (section 7 of the design; unrounded pooled estimates)", "",
          f"- P1 (JOMI and SC-GeoCCP at or above 0.85 in all four): {'holds' if P1 else 'FAILS'} "
          f"(JOMI {', '.join(f'{x:.4f}' for x in jomi)}; SC-GeoCCP {', '.join(f'{x:.4f}' for x in scg)}).",
          f"- P2 (split CP or GeoCP below 0.85 in at least one): {'holds' if P2 else 'FAILS'} (split CP {nsp} of 4, GeoCP {ngeo} of 4).",
          f"- P3 (normalized CP and bootstrap ensemble below 0.85 in fewer settings than split CP): {'holds' if P3 else 'fails'} "
          f"(normalized CP {counts['SCP stud'][0]}, bootstrap ensemble {counts['Bootstrap ensemble + residual'][0]}, split CP {nsp}).",
          ""]
    if P1 and P2:
        L.append(f"Template (positive): \"With maps from a frozen geospatial foundation model (DOFA) and a linear probe refitted on "
                 f"the training fold of every split, split CP covered under 0.85 of the selected 5% in {nsp} of four data sources "
                 f"and GeoCP in {ngeo}, whereas JOMI and SC-GeoCCP fell below 0.85 in none (SI Appendix, [section]).\"")
    elif P1:
        L.append("Template (negative, R2): \"With maps from a frozen geospatial foundation model (DOFA) and a linear probe refitted "
                 "on the training fold of every split, no published method fell below 0.85 at the selected 5% in the four data "
                 "sources, and JOMI and SC-GeoCCP met the target (SI Appendix, [section]).\"")
    else:
        L.append("R1 applies: check the code and the design conditions before writing the Results sentence.")
    open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
